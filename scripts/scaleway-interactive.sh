DO_WIZARD=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    --pack) DO_PACK=true; shift ;;
    --test) DO_TEST=true; shift ;;
    --wizard) DO_WIZARD=true; shift ;;
    --deploy-fn) DO_DEPLOY_FN=true; shift ;;
    --deploy-ct) DO_DEPLOY_CT=true; shift ;;
    --clean) DO_CLEAN=true; shift ;;
    --yes) NON_INTERACTIVE=true; shift ;;
    --dry-run) DRY_RUN=true; shift ;;
    -h|--help) print_help; exit 0 ;;
    *) log_warn "未知参数 $1"; print_help; exit 1 ;;
  esac
done

# 非交互批量（含 wizard）
if [[ "$DO_WIZARD" == true || "$DO_PACK" == true || "$DO_DEPLOY_FN" == true || "$DO_DEPLOY_CT" == true || "$DO_CLEAN" == true || "$DO_TEST" == true ]]; then
  if [[ "$DO_WIZARD" == true ]]; then
    # banner 仅在非 --yes 时显示完整，CI 时简化
    if [[ "$NON_INTERACTIVE" != true ]]; then banner; fi
    check_deps
    load_env
    wizard
    # 若仅 wizard 则退出，否则继续其他动作
    if [[ "$DO_PACK" == false && "$DO_DEPLOY_FN" == false && "$DO_DEPLOY_CT" == false && "$DO_CLEAN" == false && "$DO_TEST" == false ]]; then
      exit 0
    fi
  fi
  if [[ "$DO_PACK" == true || "$DO_DEPLOY_FN" == true || "$DO_DEPLOY_CT" == true || "$DO_CLEAN" == true || "$DO_TEST" == true ]]; then
    if [[ "$DO_WIZARD" == false ]]; then
      banner
      check_deps
      load_env
    fi
    [[ "$DO_PACK" == true ]] && do_pack
    [[ "$DO_TEST" == true ]] && do_local_test
    [[ "$DO_DEPLOY_FN" == true ]] && deploy_function
    [[ "$DO_DEPLOY_CT" == true ]] && deploy_container
    [[ "$DO_CLEAN" == true ]] && do_clean
    exit 0
  fi
fi

