log_step()  { echo -e "${BLUE}▸${NC} ${BOLD}$*${NC}"; }
log_ok()    { echo -e "${GREEN}  ✓${NC} $*"; }
log_warn()  { echo -e "${YELLOW}  ⚠${NC} $*"; }
log_err()   { echo -e "${RED}  ✗${NC} $*"; }
log_info()  { echo -e "${DIM}    $*${NC}"; }
hr()        { echo -e "${DIM}────────────────────────────────────────────────────────${NC}"; }

ask() {
  local prompt="$1" default="${2:-}" var
  if [[ "$NON_INTERACTIVE" == true ]]; then
    echo "$default"
    return
  fi
  if [[ -n "$default" ]]; then
    echo -ne "${CYAN}?${NC} ${prompt} ${DIM}[$default]${NC}: " >&2
  else
    echo -ne "${CYAN}?${NC} ${prompt}: " >&2
  fi
  read -r var || var=""
  if [[ -z "$var" ]]; then var="$default"; fi
  echo "$var"
}

ask_secret() {
  local prompt="$1" default="${2:-}" var
  if [[ "$NON_INTERACTIVE" == true ]]; then
    echo "$default"
    return
  fi
  if [[ -n "$default" ]]; then
    echo -ne "${CYAN}?${NC} ${prompt} ${DIM}[已配置, 回车保持]${NC}: " >&2
  else
    echo -ne "${CYAN}?${NC} ${prompt}: " >&2
  fi
  # masked input
  read -rs var || var=""
  echo "" >&2
  if [[ -z "$var" ]]; then var="$default"; fi
  echo "$var"
}

confirm() {
  local prompt="$1" default="${2:-y}"
  if [[ "$NON_INTERACTIVE" == true ]]; then
    [[ "$default" == "y" ]] && return 0 || return 1
  fi
  local ans
  ans=$(ask "$prompt (y/n)" "$default")
  [[ "$ans" =~ ^[Yy]$ ]] || [[ "$ans" == "是" ]]
}

generate_api_key() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 16
  else
    # fallback: /dev/urandom
    head -c 16 /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

check_deps() {
  log_step "预检依赖"
  local ok=true
  for cmd in node npm zip curl; do
    if command -v "$cmd" >/dev/null 2>&1; then
      log_ok "$cmd $( $cmd --version 2>&1 | head -n1 | tr -d '\n')"
    else
      log_err "$cmd 未安装 — 请先安装 $cmd"
      ok=false
    fi
  done
  if ! node -e "process.exit(parseInt(process.versions.node.split('.')[0])>=18?0:1)" 2>/dev/null; then
    log_err "Node.js <18，需升级到 18+ (Scaleway runtime node18/20/22)"
    ok=false
  fi
  if ! command -v scw >/dev/null 2>&1; then
    log_warn "scw CLI 未安装 — 仅影响一键部署，手动上传 zip 仍可用"
    log_info "安装: curl -s https://raw.githubusercontent.com/scaleway/scaleway-cli/master/scripts/get.sh | sh"
  else
    log_ok "scw $(scw version 2>&1 | head -n1)"
  fi
  if ! command -v docker >/dev/null 2>&1; then
    log_info "docker 未安装 — Container 部署将跳过"
  else
    log_ok "docker $(docker --version 2>&1 | head -n1)"
  fi
  hr
  if [[ "$ok" == false && "$NON_INTERACTIVE" == true ]]; then
    log_err "依赖缺失，非交互模式下无法继续"; exit 1
  fi
  if [[ "$ok" == false ]]; then
    if ! confirm "依赖不全，仍继续?" "n"; then exit 1; fi
  fi
}

load_env() {
  # 加载已有配置
  if [[ -f "$ENV_FILE" ]]; then
    # shellcheck disable=SC1090
    set -a; source "$ENV_FILE" 2>/dev/null || true; set +a
    log_info "已加载 $ENV_FILE"
  fi
  if [[ -f .env ]]; then
    log_info "检测到 .env（Docker 用），Functions 将优先使用 $ENV_FILE"
  fi
}

save_env() {
  local api_key="$1" zen_key="$2" server_pw="$3"
  cat > "$ENV_FILE" <<EOF
# Generated by scaleway-interactive.sh on $(date -Iseconds)
# 用于 Scaleway Functions / Containers 的环境变量
API_KEY=$api_key
OPENCODE_ZEN_API_KEY=$zen_key
OPENCODE_SERVER_PASSWORD=$server_pw
# 可选：覆盖端口/行为（Functions 已自动处理 PORT=8080）
# OPENCODE_PROXY_PORT=8080
# OPENCODE_DISABLE_TOOLS=true
# OPENCODE_PROXY_PROMPT_MODE=plugin-inject
EOF
  chmod 600 "$ENV_FILE"
  log_ok "配置已保存到 $ENV_FILE (600)"
}

validate_zen_key() {
  local k="$1"
  if [[ -z "$k" ]]; then return 0; fi
  if [[ ${#k} -lt 8 ]]; then
    log_warn "Zen Key 似乎过短（$((${#k})) chars），确认是否粘错？"
    return 1
  fi
  return 0
}

